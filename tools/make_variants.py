#!/usr/bin/env python3
"""
make_variants.py - Wordclock 16x16, script variants of the front, v2.0

A script variant is a front in another script for an existing language: same grid, same words, same firmware,
only every letter is replaced by a character of the other script (e.g. runes). It exists only in the 3D models:
the clock runs the firmware of the base language (config.h / wordclock_multi.yaml: language of the base).

This script writes models/lang/lang_<CODE>.scad for every entry of VARIANTS from the grid of the base language
(models/lang/lang_<BASE>.scad) and the letter table. Fillers ("x"), temperature dots, bars, "+", digits and spaces
stay as they are. Run it again after a change of the base grid; tools/check_lang.py checks every variant against
its base (same layout, every letter of the base always becomes the same character).

New variant: add an entry below (code scifi_<NAME>_<BASE>, own name, base, OpenSCAD font, FreeCAD font file,
filler default, letter table), run the script, add the include line and the LANGS entry to models/lang/lang_all.scad
and the option to the LANG line of models/Wordclock_Model.scad. Use only fonts that come with the operating
system or OpenSCAD, so nobody has to download anything.

Usage (from the repository root):  python3 tools/make_variants.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG_DIR = os.path.join(ROOT, "models", "lang")
VERSION = "v2.0"
KEEP = set("x*|+.0123456789 ")      # copied unchanged

# Anglo-Saxon runes (futhorc, the runes of the English word maps in Tolkien's books), one rune per letter.
# Digraphs (TH, NG, EA) are not combined, because every letter is one LED.
RUNES = {
    "A": "ᚪ", "B": "ᛒ", "C": "ᚳ", "D": "ᛞ", "E": "ᛖ", "F": "ᚠ", "G": "ᚷ", "H": "ᚻ", "I": "ᛁ", "J": "ᛄ",
    "K": "ᛣ", "L": "ᛚ", "M": "ᛗ", "N": "ᚾ", "O": "ᚩ", "P": "ᛈ", "Q": "ᛢ", "R": "ᚱ", "S": "ᛋ", "T": "ᛏ",
    "U": "ᚢ", "V": "ᚡ", "W": "ᚹ", "X": "ᛉ", "Y": "ᚣ", "Z": "ᛎ", "Ä": "ᚫ", "Ö": "ᛟ", "Ü": "ᚣ", "ß": "ᛋ",
}
RUNE_NOTE = ("Runes: Anglo-Saxon futhorc (Unicode block Runic U+16A0-16FF). Font Segoe UI Historic (seguihis.ttf,\n"
             "// part of Windows 10/11, nothing to download). Other systems: any font with runes, e.g. Noto Sans Runic\n"
             "// or FreeMono/FreeSerif (GNU FreeFont); FreeCAD finds one automatically (FONT_AUTO), in OpenSCAD set the\n"
             "// font name in the entry below. Segoe UI Historic has only a regular weight: the runes are thinner than\n"
             "// the bold Latin letters, fine with a front skin (FRONT_SKIN). OpenSCAD has no metrics for runes and\n"
             "// centres them roughly (size via FONT_CUSTOM_SCALE); FreeCAD measures every glyph.")

# code, own name, base, OpenSCAD font, FreeCAD font file, filler default, table, note
VARIANTS = [
    ("scifi_RUNE_GB", "Runes (English)", "GB", "Segoe UI Historic", "seguihis.ttf", "dot", RUNES, RUNE_NOTE),
    ("scifi_RUNE_DE", "Runen (Deutsch)", "DE", "Segoe UI Historic", "seguihis.ttf", "dot", RUNES, RUNE_NOTE),
]


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def strings_of(text):
    text = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("//"))
    m = re.search(r"LANG_\w+\s*=\s*\[(.*)\]\s*;", text, re.S)
    return re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)) if m else []


def convert(grid, table, base):
    out, missing = [], set()
    for row in grid:
        r = ""
        for ch in row:
            if ch in KEEP:
                r += ch
            elif ch in table:
                r += table[ch]
            else:
                missing.add(ch)
                r += ch
        out.append(r)
    if missing:
        sys.exit("ERROR %s: no character in the table for %s" % (base, " ".join(sorted(missing))))
    return out


def variant_file(code, name, base, font, fontfile, filler, table, note, grid, base_grid):
    used = sorted({c for row in base_grid for c in row if c in table}, key=lambda c: (len(c), c))
    pairs = "  ".join("%s=%s" % (c, table[c]) for c in used)
    L = []
    L.append("// lang_%s.scad - Wordclock 16x16, script variant %s of the language %s, %s" % (code, code, base, VERSION))
    L.append("// Front only: same grid, words and firmware as %s (Arduino config.h / ESPHome: choose language %s)," % (base, base))
    L.append("// only the letters are printed in another script. Generated by tools/make_variants.py from lang_%s.scad" % base)
    L.append("// - do not edit by hand, change the table in make_variants.py and run it again.")
    L.append("// Used by Wordclock_Model.scad (via lang_all.scad) and Wordclock_Model.FCMacro (reads this file).")
    L.append("// Format: [code, own name, [16 rows], OpenSCAD font, FreeCAD font file, filler, base language]")
    L.append("// " + note)
    L.append("// Letters: " + pairs)
    L.append('LANG_%s = ["%s", "%s", [' % (code, code, name))
    for i, r in enumerate(grid):
        L.append('    "%s"%s' % (r, "," if i < 15 else ""))
    L.append('], "%s", "%s", "%s", "%s"];' % (font, fontfile, filler, base))
    return "\n".join(L) + "\n"


def main():
    for code, name, base, font, fontfile, filler, table, note in VARIANTS:
        s = strings_of(read(os.path.join(LANG_DIR, "lang_%s.scad" % base)))
        if len(s) < 18:
            sys.exit("ERROR: no grid in lang_%s.scad" % base)
        grid = convert(s[2:18], table, base)
        text = variant_file(code, name, base, font, fontfile, filler, table, note, grid, s[2:18])
        p = os.path.join(LANG_DIR, "lang_%s.scad" % code)
        old = read(p) if os.path.isfile(p) else None
        if old != text:
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("written   models/lang/lang_%s.scad" % code)
        else:
            print("unchanged models/lang/lang_%s.scad" % code)


if __name__ == "__main__":
    main()
