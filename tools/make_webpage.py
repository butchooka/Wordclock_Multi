#!/usr/bin/env python3
"""
make_webpage.py - Wordclock 16x16, packs the web interface for the Arduino variant, v2.0

Reads arduino/Wordclock/webpage.html (the source, edit only this file), removes the HTML comments and leading
spaces, compresses it with gzip and writes arduino/Wordclock/webpage.h as a byte array. The clock sends it with
"Content-Encoding: gzip", every browser unpacks it. Saves approx. 20 KB flash compared to the plain text.
Run after every change of webpage.html (tools/check_lang.py reports an outdated webpage.h):
    python3 tools/make_webpage.py
"""
import gzip
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "arduino", "Wordclock", "webpage.html")
OUT = os.path.join(ROOT, "arduino", "Wordclock", "webpage.h")


def packed_html():
    with open(SRC, encoding="utf-8") as f:
        html = f.read()
    html = re.sub(r"<!--.*?-->\n?", "", html, flags=re.S)           # HTML comments
    html = "\n".join(l.strip() for l in html.splitlines() if l.strip())  # indentation, empty lines
    return html.encode("utf-8")


def build():
    raw = packed_html()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)                  # mtime 0: same input = same file
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
    text = ("/*\n  webpage.h - Wordclock 16x16, web interface (Arduino), v2.0\n"
            "  GENERATED by tools/make_webpage.py from webpage.html - do not edit, change webpage.html instead.\n"
            "  gzip-compressed HTML: %d bytes, unpacked %d bytes.\n*/\n"
            "#pragma once\n#include <Arduino.h>\n\n"
            "static const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n%s\n};\n"
            "static const size_t INDEX_HTML_GZ_LEN = sizeof(INDEX_HTML_GZ);\n") % (len(gz), len(raw), "\n".join(lines))
    return text, len(raw), len(gz)


def main():
    text, n_raw, n_gz = build()
    old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else None
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("written   webpage.h (%d bytes HTML -> %d bytes gzip)" % (n_raw, n_gz))
    else:
        print("unchanged webpage.h (%d bytes gzip)" % n_gz)


if __name__ == "__main__":
    main()
