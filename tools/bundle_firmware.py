#!/usr/bin/env python3
"""tools/bundle_firmware.py - Wordclock_Multi: firmware as few files as possible per language (e.g. for MakerWorld), v2.0

The firmware is split into several files (shared C++ in src/, language packages, core package). For a download that
needs no folder structure this script writes per language:

  ESPHome:  esphome/wordclock_multi_XX.yaml   main file + core.yaml + lang_XX.yaml as inline packages
            esphome/wordclock_multi_XX.h      all C++ files (wc_core, wc_effects, wc_font16, wc_text, wc_lang_XX)
            ESPHome cannot hold C++ inside the YAML (esphome: includes: needs a file), so it is always 2 files:
            both next to each other into /config/esphome/ (plus secrets.yaml).
  Arduino:  arduino/Wordclock_XX/Wordclock_XX.ino   sketch with config.h inserted (language fixed)
            arduino/Wordclock_XX/wordclock_bundle.h all C++ files (src/*.h of the language, webpage.h)
            The C++ stays in a .h next to the .ino: the Arduino IDE generates function prototypes only for code
            inside the .ino, code from the headers would get prototypes before its types and not compile.

Plus README.txt and two zips (Wordclock_ESPHome.zip, Wordclock_Arduino.zip) for the upload.
Output: output/makerworld/ (not in the repository). Needs Python 3 only, takes about a second.
Call:  python tools/bundle_firmware.py [DE GB ...] [--out DIR] [--no-zip]   (or double-click tools/bundle_firmware.bat)
Exit code 1 on an error (missing file, a line that was expected but not found).
"""
import argparse
import pathlib
import re
import shutil
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SKETCH = ROOT / "arduino" / "Wordclock"
SRC = SKETCH / "src"                                   # single source of the C++ files (see sync_src.py)
ESP = ROOT / "esphome"
ESP_MAIN = ESP / "wordclock_multi.yaml"
ESP_CORE = ESP / "wordclock_multi" / "core.yaml"
ESP_LANG = ESP / "wordclock_multi" / "lang"

INC_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')
PRAGMA_RE = re.compile(r"^\s*#\s*pragma\s+once\b")


def read(p):
    return p.read_text(encoding="utf-8")


def write(p, text):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")


def need(cond, msg):
    if not cond:
        raise ValueError(msg)


# ------------------------------------------------------------------ C++ ------------------------------------------------
def inline_cpp(path, seen):
    """Text of path with every local #include "..." inserted (each file once, #pragma once removed).
    Includes that are no file next to it (system headers like "esp_sntp.h") stay as they are."""
    out = []
    for line in read(path).splitlines():
        if PRAGMA_RE.match(line):
            continue
        m = INC_RE.match(line)
        inc = (path.parent / m.group(1)).resolve() if m else None
        if inc is None or not inc.is_file():
            out.append(line)
            continue
        if inc in seen:
            continue
        seen.add(inc)
        name = inc.name
        out.append("// ===== begin %s =====" % name)
        out.extend(inline_cpp(inc, seen))
        out.append("// ===== end %s =====" % name)
    return out


def cpp_bundle(files, title):
    seen = set()
    out = ["// %s" % title,
           "// Generated by tools/bundle_firmware.py from the Wordclock_Multi sources - do not edit, changes get lost.",
           "// Source: https://github.com/butchooka/Wordclock_Multi",
           "#pragma once"]
    for f in files:
        f = f.resolve()
        need(f.is_file(), "file not found: %s" % f)
        if f in seen:
            continue
        seen.add(f)
        out.append("// ===== begin %s =====" % f.name)
        out.extend(inline_cpp(f, seen))
        out.append("// ===== end %s =====" % f.name)
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ ESPHome --------------------------------------------
def indent(text, n):
    pad = " " * n
    return "\n".join(pad + l if l.strip() else "" for l in text.rstrip("\n").splitlines())


def esphome_bundle(code, hname):
    main = read(ESP_MAIN)
    core = read(ESP_CORE)
    lang = read(ESP_LANG / ("lang_%s.yaml" % code))

    # language package: name / friendly_name are set in the main file (rename in the dashboard needs exactly one),
    # its include of wc_lang_XX.h is part of the bundle header
    lang, n = re.subn(r"(?m)^  (name|friendly_name):.*\n", "", lang)
    lang, n = re.subn(r"(?m)^esphome:\n  includes:\n(    - \$\{src_dir\}/\S+\n?)+", "", lang)
    need(n == 1, "lang_%s.yaml: block 'esphome: includes:' not found" % code)

    # core package: the list of .h files becomes the one bundle header
    lines, done = [], False
    for l in core.splitlines():
        if re.match(r"^    - \$\{src_dir\}/\S+\.h\s*$", l):
            if not done:
                lines.append("    - %s" % hname)
                done = True
            continue
        lines.append(l)
    need(done, "core.yaml: no include '- ${src_dir}/...h' found")
    core = "\n".join(lines)

    # main file: own header instead of the comment block, packages inline, no src_dir
    i = main.find("\npackages:\n")
    need(i >= 0, "wordclock_multi.yaml: 'packages:' not found")
    body = main[i + 1:]
    body, n1 = re.subn(r"(?m)^  lang: !include .*$", lambda m: "  lang:\n" + indent(lang, 4), body, count=1)
    body, n2 = re.subn(r"(?m)^  core: !include .*$", lambda m: "  core:\n" + indent(core, 4), body, count=1)
    need(n1 == 1 and n2 == 1, "wordclock_multi.yaml: lines 'lang: !include' / 'core: !include' not found")
    body = re.sub(r"(?m)^  src_dir:.*\n", "", body)
    head = """# wordclock_multi_%(c)s.yaml - Wordclock 16x16, ESPHome, language %(c)s, single-file version v2.0
# Generated by tools/bundle_firmware.py (https://github.com/butchooka/Wordclock_Multi).
# Files: this .yaml and wordclock_multi_%(c)s.h next to each other in /config/esphome/, secrets.yaml next to them:
#   wifi_ssid, wifi_password, ap_password, api_key, ota_password
# Normally only edit the part after "packages:" (name, pins, Home Assistant entities, board).
# SEVERAL CLOCKS: one copy of this file per clock (e.g. wortuhr-kueche.yaml) with its own name: - the .h is shared.
# Renaming in the ESPHome dashboard (... > Rename) works (name is a substitution of this file).
# Other language: download the file pair of that language (the language is inside the packages below).
""" % {"c": code}
    return head + "\n" + body.rstrip("\n") + "\n"


# ------------------------------------------------------------------ Arduino --------------------------------------------
def arduino_bundle(code, sketch_name, hname):
    ino = read(SKETCH / "Wordclock.ino")
    cfg = read(SKETCH / "config.h")

    # config.h: language fixed, no wc_build.h (only used by build_firmware.bat)
    a = cfg.find("// build_firmware.bat writes")
    b = cfg.find("// ============================ HARDWARE")
    need(a >= 0 and b > a, "config.h: language section not found")
    cfg = (cfg[:a] + "// ============================ LANGUAGE ============================\n"
           "// Fixed in this single-file version: %s (src/wc_lang_%s.h, inside %s).\n"
           "// Other language: download the sketch folder of that language.\n\n" % (code, code, hname) + cfg[b:])
    cfg = "\n".join(l for l in cfg.splitlines() if not PRAGMA_RE.match(l))

    headers, out, put = [], [], False
    for l in ino.splitlines():
        m = INC_RE.match(l)
        if m and m.group(1) == "config.h":
            out.append("// ===== begin config.h (settings: language, hardware) =====")
            out.extend(cfg.splitlines())
            out.append("// ===== end config.h =====")
            continue
        if re.match(r"^\s*#\s*include\s+WC_LANG_FILE\b", l):
            headers.append(SRC / ("wc_lang_%s.h" % code))
        elif m and (SKETCH / m.group(1)).is_file():
            headers.append(SKETCH / m.group(1))
        else:
            out.append(l)
            continue
        if not put:
            out.append('#include "%s"   // all C++ files of the sketch (src/*.h, language %s, webpage.h)' % (hname, code))
            put = True
    need(put and any(h.name == "wc_lang_%s.h" % code for h in headers), "Wordclock.ino: includes not found")

    note = ("  SINGLE-FILE VERSION, language %s (generated by tools/bundle_firmware.py):\n"
            "  folder %s/ with %s.ino (settings from config.h further down) and %s (all C++ files).\n"
            "  The folder name must stay the same as the .ino name (Arduino IDE).\n" % (code, sketch_name, sketch_name, hname))
    ino_text = "\n".join(out) + "\n"
    ino_text = ino_text.replace("/*\n", "/*\n" + note + "\n", 1)
    return ino_text, cpp_bundle(headers, "%s - Wordclock 16x16, Arduino, language %s, all C++ files" % (hname, code))


# ------------------------------------------------------------------ main -----------------------------------------------
README = """Wordclock 16x16 - firmware single-file versions / Firmware als Einzeldateien (v2.0)
Source / Quelle: https://github.com/butchooka/Wordclock_Multi   (XX = language code / Sprachcode)

ESPHome (Home Assistant)  -  Wordclock_ESPHome.zip / esphome/
  EN: copy wordclock_multi_XX.yaml AND wordclock_multi_XX.h to /config/esphome/ (secrets.yaml next to them:
      wifi_ssid, wifi_password, ap_password, api_key, ota_password). Edit name, led_pin and the Home Assistant
      entities in the .yaml, then Install. Several clocks: one copy of the .yaml per clock with its own name.
  DE: wordclock_multi_XX.yaml UND wordclock_multi_XX.h nach /config/esphome/ kopieren (secrets.yaml daneben:
      wifi_ssid, wifi_password, ap_password, api_key, ota_password). In der .yaml name, led_pin und die
      Home-Assistant-Entitäten eintragen, dann Install. Mehrere Uhren: je Uhr eine Kopie der .yaml mit eigenem name.

Arduino (stand-alone, web interface / eigenständig, Weboberfläche)  -  Wordclock_Arduino.zip / arduino/
  EN: open the folder Wordclock_XX/Wordclock_XX.ino in the Arduino IDE (ESP32 board package 2.0.x or 3.x, with 2.0.x
      also the library "Adafruit NeoPixel"), check the settings (LED_PIN ...) at the top, upload via USB.
  DE: Ordner Wordclock_XX/Wordclock_XX.ino in der Arduino IDE öffnen (ESP32-Boardpaket 2.0.x oder 3.x, bei 2.0.x
      zusätzlich Bibliothek "Adafruit NeoPixel"), Einstellungen (LED_PIN ...) oben prüfen, per USB hochladen.

Languages / Sprachen: %s
"""


def all_codes():
    return sorted(p.stem[len("wc_lang_"):] for p in SRC.glob("wc_lang_*.h"))


def zip_dir(src, zpath):
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(src.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(src.parent))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("langs", nargs="*", help="language codes (default: all), e.g. DE GB dialect_BAD")
    ap.add_argument("--out", default=str(ROOT / "output" / "makerworld"), help="output folder")
    ap.add_argument("--no-zip", action="store_true", help="do not write the zips")
    a = ap.parse_args()

    codes = a.langs or all_codes()
    out = pathlib.Path(a.out)
    for sub in ("esphome", "arduino"):
        shutil.rmtree(out / sub, ignore_errors=True)
    errors = 0
    for c in codes:
        try:
            need((SRC / ("wc_lang_%s.h" % c)).is_file(), "src/wc_lang_%s.h not found" % c)
            hname = "wordclock_multi_%s.h" % c
            core_h = [SRC / n for n in ("wc_core.h", "wc_effects.h", "wc_font16.h", "wc_text.h")]
            write(out / "esphome" / ("wordclock_multi_%s.yaml" % c), esphome_bundle(c, hname))
            write(out / "esphome" / hname,
                  cpp_bundle(core_h + [SRC / ("wc_lang_%s.h" % c)],
                             "%s - Wordclock 16x16, ESPHome, language %s, all C++ files" % (hname, c)))
            sk = "Wordclock_%s" % c
            ino, h = arduino_bundle(c, sk, "wordclock_bundle.h")
            write(out / "arduino" / sk / (sk + ".ino"), ino)
            write(out / "arduino" / sk / "wordclock_bundle.h", h)
            print("ok      %s" % c)
        except (ValueError, FileNotFoundError) as e:
            errors += 1
            print("ERROR   %s: %s" % (c, e))
    write(out / "README.txt", README % ", ".join(codes))
    if not a.no_zip and not errors:
        zip_dir(out / "esphome", out / "Wordclock_ESPHome.zip")
        zip_dir(out / "arduino", out / "Wordclock_Arduino.zip")
    print("\n%d languages, %d errors -> %s" % (len(codes), errors, out))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
