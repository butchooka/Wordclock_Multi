def all_codes():
    return sorted(p.stem[len("wc_lang_"):] for p in SRC.glob("wc_lang_*.h"))


def zip_dir(src, zpath, prefix):
    zpath.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(src.rglob("*")):
            if f.is_file():
                z.write(f, pathlib.PurePosixPath(prefix) / f.relative_to(src).as_posix())


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("langs", nargs="*", help="language codes (default: all), e.g. DE GB dialect_BAD")
    ap.add_argument("--no-zip", action="store_true", help="do not write the zips")
    a = ap.parse_args()

    codes = a.langs or all_codes()
    out_esp = ESP / "single_Language"
    out_ino = ROOT / "arduino" / "single_Language"
    out_mw = ROOT / "_private" / "makerworld"
    if not a.langs:                                    # complete run: remove languages that no longer exist
        for d in (out_esp, out_ino):
            shutil.rmtree(d, ignore_errors=True)
    errors = 0
    for c in codes:
        try:
            need((SRC / ("wc_lang_%s.h" % c)).is_file(), "src/wc_lang_%s.h not found" % c)
            hname = "wordclock_multi_%s.h" % c
            core_h = [SRC / n for n in ("wc_core.h", "wc_effects.h", "wc_font16.h", "wc_text.h")]
            write(out_esp / ("wordclock_multi_%s.yaml" % c), esphome_bundle(c, hname))
            write(out_esp / hname,
                  cpp_bundle(core_h + [SRC / ("wc_lang_%s.h" % c)],
                             "%s - Wordclock 16x16, ESPHome, language %s, all C++ files" % (hname, c)))
            sk = "Wordclock_%s" % c
            ino, h = arduino_bundle(c, sk, "wordclock_bundle.h")
            write(out_ino / sk / (sk + ".ino"), ino)
            write(out_ino / sk / "wordclock_bundle.h", h)
            print("ok      %s" % c)
        except (ValueError, FileNotFoundError) as e:
            errors += 1
            print("ERROR   %s: %s" % (c, e))
    done = ", ".join(all_codes())
    write(out_esp / "README.md", README_ESP % done)
    write(out_ino / "README.md", README_INO % done)
    if not a.no_zip and not errors:
        write(out_mw / "README.txt", README % done)
        zip_dir(out_esp, out_mw / "Wordclock_ESPHome.zip", "esphome")
        zip_dir(out_ino, out_mw / "Wordclock_Arduino.zip", "arduino")
    print("\n%d languages, %d errors -> %s, %s" % (len(codes), errors, out_esp.relative_to(ROOT), out_ino.relative_to(ROOT)))
    if not a.no_zip and not errors:
        print("zips + README.txt -> %s" % out_mw.relative_to(ROOT))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
