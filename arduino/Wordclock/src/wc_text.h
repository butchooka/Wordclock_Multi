/*
  wc_text.h - Wordclock 16x16, text ticker (Arduino + ESPHome), v1.0
  Shows a text letter by letter, every letter as large as the whole matrix (16 x 16 LEDs).
  Font: src/wc_font16.h (generated by tools/make_font.py): Latin, Greek, Cyrillic, digits, punctuation, € and ♥.
  Lower case is shown as capitals, characters without a glyph (e.g. Chinese, Japanese, Korean) are skipped.

  Timing (WC_TXT_*): every letter fades in, stays and fades out, a short dark pause between two letters
  (so that double letters stay readable), a space is a longer pause.
  The text always runs WC_TXT_PASSES times, with a pause of WC_TXT_END between two passes.
*/
#pragma once
#include "wc_core.h"
#include "wc_font16.h"

#define WC_TXT_MAX     64      // maximum number of characters (code points) of the text
#define WC_TXT_ON      0.65f   // seconds a letter is visible (incl. fade in/out)
#define WC_TXT_FADE    0.08f   // seconds fade in and fade out
#define WC_TXT_GAP     0.15f   // seconds dark between two letters
#define WC_TXT_SPACE   0.55f   // seconds dark for a space
#define WC_TXT_END     2.00f   // seconds dark between two passes
#define WC_TXT_PASSES  2       // number of passes

// glyph number of a code point, -1 = no glyph
static inline int wc_font_find(uint32_t cp) {
  int lo = 0, hi = WC_FONT16_N - 1;
  while (lo <= hi) {
    const int mid = (lo + hi) / 2;
    const uint32_t v = WC_FONT16_IDX[mid].cp;
    if (v == cp) return WC_FONT16_IDX[mid].g;
    if (v < cp) lo = mid + 1; else hi = mid - 1;
  }
  return -1;
}

// next code point of a UTF-8 string, advances s
static inline uint32_t wc_u8_next(const char *&s) {
  const unsigned char c = (unsigned char)*s;
  const int n = wc_u8len(c);
  uint32_t cp = (n == 1) ? c : (n == 2) ? (c & 0x1F) : (n == 3) ? (c & 0x0F) : (c & 0x07);
  s++;
  for (int i = 1; i < n && (*s & 0xC0) == 0x80; i++, s++) cp = (cp << 6) | (*s & 0x3F);
  return cp;
}

// Prepared text: glyph numbers (-1 = space / pause), built once with wc_text_set()
struct WcText {
  int16_t g[WC_TXT_MAX];
  uint8_t n;
  float pass;        // seconds for one pass incl. the end pause
};

static inline void wc_text_set(WcText &t, const char *utf8) {
  t.n = 0;
  t.pass = 0.0f;
  if (!utf8) return;
  const char *s = utf8;
  while (*s && t.n < WC_TXT_MAX) {
    const uint32_t cp = wc_u8_next(s);
    if (cp == ' ' || cp == '\t' || cp == '\n' || cp == '_') {
      if (t.n && t.g[t.n - 1] == -1) continue;   // several spaces = one pause
      t.g[t.n++] = -1;
      continue;
    }
    const int g = wc_font_find(cp);
    if (g >= 0) t.g[t.n++] = (int16_t)g;
  }
  while (t.n && t.g[t.n - 1] == -1) t.n--;        // no pause at the end
  for (int i = 0; i < t.n; i++) t.pass += (t.g[i] < 0) ? WC_TXT_SPACE : (WC_TXT_ON + WC_TXT_GAP);
  if (t.n) t.pass += WC_TXT_END;
}

// true while something is (still) to be shown: ts = seconds since start.
// WC_TXT_PASSES passes, no pause after the last one.
static inline bool wc_text_running(const WcText &t, float ts) {
  if (!t.n || t.pass <= 0.0f) return false;
  return ts < WC_TXT_PASSES * t.pass - WC_TXT_END;
}

// draws the frame for ts seconds after the start; rainbow = every letter gets the next colour of the rainbow
static inline void wc_text_render(const WcText &t, float ts, WcRgb color, bool rainbow, WcRgb *f) {
  memset(f, 0, sizeof(WcRgb) * WC_N);
  if (!t.n || t.pass <= 0.0f) return;
  float p = fmodf(ts, t.pass);
  int letter = 0;
  for (int i = 0; i < t.n; i++) {
    if (t.g[i] < 0) {
      if (p < WC_TXT_SPACE) return;
      p -= WC_TXT_SPACE;
      continue;
    }
    if (p < WC_TXT_ON + WC_TXT_GAP) {
      if (p >= WC_TXT_ON) return;                  // pause between two letters
      float v = 1.0f;
      if (p < WC_TXT_FADE) v = p / WC_TXT_FADE;
      else if (p > WC_TXT_ON - WC_TXT_FADE) v = (WC_TXT_ON - p) / WC_TXT_FADE;
      WcRgb c = color;
      if (rainbow) wc_hsv((float)(letter * 47 % 360), 1.0f, 1.0f, c);
      c = wc_scale(c, v);
      const uint16_t *rows = WC_FONT16[t.g[i]];
      for (int r = 0; r < WC_ROWS; r++)
        for (int col = 0; col < WC_COLS; col++)
          if (rows[r] & (0x8000u >> col)) f[r * WC_COLS + col] = c;
      return;
    }
    p -= WC_TXT_ON + WC_TXT_GAP;
    letter++;
  }
}
